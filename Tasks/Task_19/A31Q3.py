# Input            : Directory name (command line argument)
# Output           : Deletes duplicate files and logs removed files into Log.txt
# Description      : Traverses a directory recursively, calculates MD5 checksum
#                    for each file, detects duplicate files, and removes
#                    duplicate copies while keeping one original.
